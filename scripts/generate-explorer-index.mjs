// Writes explorer/src/app/stories-index.ts with an import per story file, the Figma URL of the
// matching Code Connect template when there is one and the imports the component needs in an app.
// Run: npm run explorer:index
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const config = JSON.parse(readFileSync(join(root, 'figma.config.json'), 'utf8'));
const substitutions = Object.entries(config.codeConnect?.documentUrlSubstitutions ?? {});
const componentsDir = join(root, 'src/components');

const compact = (name) => name.replace(/[-_]/g, '').toLowerCase();

function figmaUrl(dir, storyBase, figmaFiles) {
  const match = figmaFiles.find((f) => compact(f.replace('.figma.ts', '')) === compact(storyBase)) ?? figmaFiles[0];
  if (!match) return undefined;
  const line = readFileSync(join(dir, match), 'utf8').match(/^\/\/ url=(.+)$/m);
  if (!line) return undefined;
  return substitutions.reduce((url, [key, value]) => url.replace(key, value), line[1].trim());
}

// Story-only modules: Storybook runtime and the sample data/helpers of the stories.
const STORY_ONLY = /^(@storybook\/|storybook\/|\.\.\/\.\.\/stories\/)/;

/** Real imports a component needs, taken from the story source; DS files map to the package name. */
function codeImports(source) {
  const byModule = new Map();
  for (const [, typeOnly, specifiers, from] of source.matchAll(/^import\s+(type\s+)?\{([^}]+)\}\s+from\s+'([^']+)';/gm)) {
    if (typeOnly || STORY_ONLY.test(from)) continue;
    const module = from.startsWith('.') ? 'prime-one-ds' : from;
    const names = specifiers
      .split(',')
      .map((name) => name.trim())
      .filter((name) => name && !name.startsWith('type '));
    if (!names.length) continue;
    byModule.set(module, [...new Set([...(byModule.get(module) ?? []), ...names])]);
  }
  const rank = (module) => (module.startsWith('@angular/') ? 0 : module === 'prime-one-ds' ? 2 : 1);
  return [...byModule.entries()]
    .sort(([a], [b]) => rank(a) - rank(b) || a.localeCompare(b))
    .map(([module, names]) => `import { ${names.join(', ')} } from '${module}';`);
}

const entries = [];
for (const folder of readdirSync(componentsDir, { withFileTypes: true })) {
  if (!folder.isDirectory()) continue;
  const dir = join(componentsDir, folder.name);
  const files = readdirSync(dir);
  const figmaFiles = files.filter((f) => f.endsWith('.figma.ts')).sort();
  for (const story of files.filter((f) => f.endsWith('.stories.ts')).sort()) {
    const base = story.replace('.stories.ts', '');
    entries.push({
      path: `../../../src/components/${folder.name}/${base}.stories`,
      url: figmaUrl(dir, base, figmaFiles),
      imports: codeImports(readFileSync(join(dir, story), 'utf8')),
    });
  }
}
entries.sort((a, b) => a.path.localeCompare(b.path));

const lines = ['// Generated by scripts/generate-explorer-index.mjs. Do not edit by hand.'];
entries.forEach((entry, i) => lines.push(`import * as m${i} from '${entry.path}';`));
lines.push('', 'export const STORY_MODULES: { module: object; figmaUrl?: string; imports: string[] }[] = [');
entries.forEach((entry, i) =>
  lines.push(`  { module: m${i}${entry.url ? `, figmaUrl: '${entry.url}'` : ''}, imports: ${JSON.stringify(entry.imports)} },`),
);
lines.push('];', '');

const out = join(root, 'explorer/src/app/stories-index.ts');
writeFileSync(out, lines.join('\n'));
console.log(`${entries.length} stories -> ${out}`);
